import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import ts from 'typescript';
import prettier from 'prettier';
import { modules, stateWrites } from '../packages/contracts/dist/metadata.js';
import { contractExamples } from '../packages/contracts/dist/examples.js';

const printer = ts.createPrinter({ removeComments: true, newLine: ts.NewLineKind.LineFeed });
function compiledSignatures(files) {
  return files
    .flatMap((file) => {
      const path = resolve('packages/contracts/dist', file);
      if (!existsSync(path)) return [];
      const source = ts.createSourceFile(
        path,
        readFileSync(path, 'utf8'),
        ts.ScriptTarget.Latest,
        true
      );
      return source.statements
        .filter((node) => !ts.isImportDeclaration(node) && !ts.isExportDeclaration(node))
        .map((node) => printer.printNode(ts.EmitHint.Unspecified, node, source));
    })
    .join('\n');
}

function signatures(module) {
  const files = module.files.map((file) => file.replace(/^src\//u, '').replace(/\.ts$/u, '.d.ts'));
  if (module.id === 'task' || module.id === 'delivery')
    files.push(
      ...files
        .filter((file) => file.startsWith('task/') && !file.includes('cooperation'))
        .map((file) => file.replace('.d.ts', '-v2.d.ts'))
    );
  if (module.id === 'runtime') files.push('dsh/pool-v2.d.ts', 'dsh/execution.d.ts');
  if (module.id === 'task' || module.id === 'delivery')
    files.push(
      ...files
        .filter((file) => file.endsWith('-v2.d.ts'))
        .map((file) => file.replace('-v2.d.ts', '-v3.d.ts'))
    );
  if (module.id === 'media') files.push('media-result.d.ts');
  return compiledSignatures(files);
}

function section(module) {
  const versionNote =
    module.id === 'task'
      ? '生产使用 V3 接口及 create…V3 工厂；v1/v2 声明保留兼容。\n\n'
      : module.id === 'delivery'
        ? '生产使用 V3 接口及 create…V3 工厂；v1/v2 声明保留兼容。\n\n'
        : '';
  const examples = contractExamples.filter((example) => example.module === module.id);
  const writes = stateWrites.filter((state) =>
    state.owners.some((owner) => module.files.includes(owner))
  );
  const ownership = writes.length
    ? '\n\n持久化写入能力：' +
      writes
        .map(
          (write) =>
            '`' + write.domain + '` → `' + write.type + '`（`' + write.owners.join('`, `') + '`）'
        )
        .join('；') +
      '。'
    : '';
  const examplesText = examples
    .map(
      (example) =>
        '### ' +
        example.kind +
        '：`' +
        example.id +
        '`\n\n```json\n' +
        JSON.stringify({ input: example.input, expected: example.expected }, null, 2) +
        '\n```'
    )
    .join('\n\n');
  return `## ${module.title}\n\n版本：${module.version}；Owner：${module.owner}；公共入口：\`${module.entry}\`。\n\n### 1. 职责边界\n\n${module.responsibility}。\n\n### 2. 编译接口\n\n${versionNote}\`\`\`ts\n${signatures(module)}\n\`\`\`\n\n### 3. 不变量\n\n${module.invariants.join('；')}。${ownership}\n\n### 4. 前后条件\n\n前置：${module.preconditions}。\n\n后置：${module.postconditions}。\n\n### 5. 错误契约\n\n${module.errors}。跨模块结果使用 \`Result<T>\` / \`ContractFailure\`，稳定错误分类、重试语义和根因关联不替换既有记录字段。兼容入口的降级由消费者显式选择。\n\n### 6. 副作用与能力\n\n${module.capabilities.length ? '允许的注入能力和默认适配器：' + module.capabilities.map((capability) => '`' + capability + '`').join('、') + '。文件范围为配置、状态目录、所属 Task 工作区和队列独立文件目录，依接口参数绑定。' : '无副作用；纯计算模块不适用网络、文件、子进程及后台关闭。'}\n\n模块依赖：${module.dependencies.length ? module.dependencies.map((dependency) => '`' + dependency + '`').join('、') : '无；共享值来自独立契约包'}。\n\n### 7. 幂等、并发与生命周期\n\n${module.concurrency}。同步纯计算不适用事件投递、退订和关闭；异步接口以输入消息/Task/lane/execution/lease/票据身份作为幂等键，观察者异常不阻止持久化后的结算。\n\n### 8. 数据时效\n\n${module.freshness}。缺失 \`NOT_FOUND\`、过期 \`STALE_DATA\`、读取失败 \`UPSTREAM_FAILED\` / \`PERSISTENCE_FAILED\` 分别表达；无 TTL 的历史和纯值不伪造过期状态。\n\n### 9. 兼容策略\n\n${module.compatibility}。消费者基线：\`packages/contracts/compatibility/v1\`；破坏性修改通过新版本接口迁移。\n\n### 10. 可执行示例\n\n以下夹具由消费者测试和 \`node scripts/smoke-contracts.mjs ${module.id}\` 直接执行；failure 可以是显式拒绝或契约规定的部分降级。\n\n${examplesText}\n`;
}

export async function generateContracts() {
  const table = modules
    .map((module) => `| ${module.title} | \`${module.entry}\` | ${module.version} |`)
    .join('\n');
  const text =
    '# 模块契约\n\n<!-- Generated by scripts/generate-contracts.mjs from independent TypeScript declarations, metadata and executable fixtures. Do not edit. -->\n\n现行行为以 ADR-001、ADR-002、[ADR-003](adr/003-enforced-module-contracts.md) 、[ADR-006](adr/006-lane-cooperation.md) 和 [ADR-009](adr/009-persistent-session-lanes.md) 为基准。所有生产文件按职责归属到以下 12 模块；`src/main.ts` 是唯一装配入口。旧目录兼容路径及 `tests/legacy` 保存历史，不是新增生产入口。\n\n| 模块 | 公共入口 | 版本 |\n| --- | --- | --- |\n' +
    table +
    '\n\n## 共享基础契约\n\n以下类型与错误由独立契约包提供；工厂签名是类型，运行值由模块公共入口提供。快照隔离内部引用，稳定错误包含重试语义和根因关联。\n\n```ts\n' +
    compiledSignatures(['readonly.d.ts', 'errors.d.ts', 'health-probe.d.ts']) +
    '\n```\n\n' +
    modules.map(section).join('\n');
  return prettier.format(text, {
    parser: 'markdown',
    ...(await prettier.resolveConfig('docs/MODULE-CONTRACTS.md')),
  });
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const generated = await generateContracts();
  const path = resolve('docs/MODULE-CONTRACTS.md');
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== generated) {
      console.error('契约文档已漂移：运行 npm run contracts:generate 并提交产物。');
      process.exitCode = 1;
    } else console.log('契约文档与独立编译声明、元数据和可执行示例一致。');
  } else writeFileSync(path, generated);
}
